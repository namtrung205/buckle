/**
 * Verified moving-load data for the landing's truss illustration.
 *
 * WHAT THIS IS
 * A six-panel simply-supported Pratt deck truss, solved offline by the plane
 * -truss direct stiffness method. The numbers below are the solved response,
 * not artistic values: the illustration reads them, it does not invent them.
 *
 * MODEL
 *   Span      6 panels x 80 units, deck (bottom chord) at y = 130, top chord
 *             at y = 30. Inclined end posts, five verticals, four Pratt
 *             diagonals sloping down toward midspan.
 *   Statics   12 nodes, 21 members, 3 reactions -> 2n = m + r = 24, so the
 *             truss is statically determinate and stable.
 *   Supports  B0 pinned (ux = uy = 0), B6 roller (uy = 0). Both are deck nodes,
 *             and the drawn support symbols sit on those node coordinates.
 *   Sections  EA = 1 for every member (uniform, normalised).
 *   Load      A single downward unit load, P = 1, applied to the deck.
 *
 * SOLUTION
 * One load case per deck panel point B0..B6. Reactions come out at the exact
 * statics values (load at B1 -> 5/6 and 1/6, at B3 -> 1/2 and 1/2, and so on),
 * vertical equilibrium closes to 1.0 in every case, and load positions
 * mirrored about midspan produce exactly mirrored member forces.
 *
 * BETWEEN PANEL POINTS
 * The load is distributed linearly to the two adjacent deck nodes -- at 30 %
 * of a panel, 70 % goes to the near node and 30 % to the far one, so the total
 * applied load stays exactly 1. The structure is linear-elastic, so the
 * response for that split is the same linear blend of the two panel-point
 * solutions. The component therefore interpolates FORCES and DISPLACEMENTS
 * with the same weights, which is exact rather than an approximation.
 *
 * SIGN CONVENTION
 * Member force positive = tension, negative = compression. `FORCE_MAX` is the
 * largest magnitude over every case and is used as a single global colour
 * scale, so intensity is comparable between frames.
 *
 * DISPLACEMENTS
 * `DISPLACEMENTS[case]` is [ux, uy] per node in node order, computed with
 * EA = 1 and P = 1. They are not physical millimetres; `DISP_SCALE` maps the
 * largest deflection in the whole dataset (851.43 units) onto
 * 22 px of drawing, which is why the legend says normalised
 * rather than quoting an amplification factor that would only mean something
 * next to a real EA.
 *
 * Regenerated by hand only. See the tests in ./__tests__/truss-data.test.ts,
 * which re-derive the reactions and the symmetry from this table.
 */

