/**
 * Blend the two bracketing panel-point solutions for a load at `s` in [0, 1]
 * along the deck. Returns forces, nodal displacements and the applied nodal
 * load vector, whose entries always sum to exactly 1.
 */
export function stateAt(s: number) {
  const t = Math.min(1, Math.max(0, s)) * (DECK.length - 1);
  const i = Math.min(DECK.length - 2, Math.floor(t));
  const w = t - i;
  const mix = (rows: number[][]) => rows[i].map((v, k) => v * (1 - w) + rows[i + 1][k] * w);
  const load = DECK.map((_, k) => (k === i ? 1 - w : k === i + 1 ? w : 0));
  return { forces: mix(FORCES), displacements: mix(DISPLACEMENTS), load, panel: i, fraction: w };
}
